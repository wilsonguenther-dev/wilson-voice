//! Y8-C — **earcons**: four short, Yappy-voiced sounds for start, stop, paste
//! and achievement. Off by default, one setting.
//!
//! ## Why the ORDER is the whole item
//!
//! YV28 mutes the Mac's whole output while a take records and restores the
//! exact prior state when it ends. A start earcon played "at start" therefore
//! lands on a muted device and the user hears nothing; a stop earcon played
//! "at stop" before the restore does the same. So this module owns both halves
//! of a take's audio, and it owns them in ONE order:
//!
//! * [`start_take`] — play the start earcon to completion, THEN mute.
//! * [`end_take`] — restore the output, THEN play the stop earcon.
//!
//! `lib.rs` reaches the output device ONLY through these two functions (a test
//! in `tests/earcons.rs` scans `lib.rs` to keep it that way), so the ordering a
//! test asserts here is the ordering the app runs.
//!
//! ## What never plays
//!
//! * Anything while a meeting records — it would land on the recording. The
//!   gate is the same [`TakeContext`] that keeps YV91's auto-mute off a meeting,
//!   so one question ("is a meeting capturing?") answers both rules.
//! * Anything when the setting is off — which is the default.
//! * Anything for a state change that is not one of these four [`Earcon`]s.
//!
//! ## Bundled, never fetched
//!
//! The WAVs live in `assets/sounds/` (generated by `scripts/gen-earcons.py`),
//! are listed in `tauri.conf.json` bundle resources, and are compiled INTO the
//! binary with `include_bytes!` — a missing asset is a build error, not a
//! silent runtime failure, and there is nothing to download.

use crate::meeting::TakeContext;
use crate::sysaudio::{mute_for_take, OutputAudioState, OutputControl};

/// The four sounds, and the only four.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Earcon {
    /// Recording started — "I'm listening".
    Start,
    /// Recording stopped (release, tap or cancel) — "got it".
    Stop,
    /// The take was pasted into the focused app.
    Paste,
    /// The take crossed a lifetime word milestone (see [`WORD_MILESTONES`]).
    Achievement,
}

impl Earcon {
    /// Every earcon, in a fixed order. Exactly four, by spec.
    pub const ALL: [Earcon; 4] = [
        Earcon::Start,
        Earcon::Stop,
        Earcon::Paste,
        Earcon::Achievement,
    ];

    /// The asset's file name under `assets/sounds/`.
    pub fn file_name(self) -> &'static str {
        match self {
            Earcon::Start => "dictation-start.wav",
            Earcon::Stop => "dictation-stop.wav",
            Earcon::Paste => "paste.wav",
            Earcon::Achievement => "achievement.wav",
        }
    }

    /// The WAV bytes, embedded at compile time.
    pub fn bytes(self) -> &'static [u8] {
        match self {
            Earcon::Start => include_bytes!("../assets/sounds/dictation-start.wav"),
            Earcon::Stop => include_bytes!("../assets/sounds/dictation-stop.wav"),
            Earcon::Paste => include_bytes!("../assets/sounds/paste.wav"),
            Earcon::Achievement => include_bytes!("../assets/sounds/achievement.wav"),
        }
    }
}

/// Where an earcon goes. The app's sink is [`SystemSink`]; tests record calls.
pub trait EarconSink {
    /// Play `earcon` and return only once it has finished sounding. Used for
    /// the start earcon, which must be OVER before the mute lands.
    fn play_blocking(&self, earcon: Earcon);
    /// Play `earcon` without waiting for it.
    fn play(&self, earcon: Earcon);
}

/// The one rule: the setting is on AND the take is a plain dictation. A meeting
/// recording, or a dictation taken while one records, never plays a sound.
pub fn earcon_allowed(enabled: bool, context: TakeContext) -> bool {
    enabled && matches!(context, TakeContext::Dictation)
}

/// A take starts: the start earcon plays to completion, THEN the output is
/// muted (when `mute_while_dictating` is on and the context allows it).
/// Returns what the mute saved, for [`end_take`] to put back.
pub fn start_take<S: EarconSink + ?Sized, O: OutputControl + ?Sized>(
    earcons_enabled: bool,
    mute_while_dictating: bool,
    context: TakeContext,
    sink: &S,
    output: &O,
) -> Option<OutputAudioState> {
    if earcon_allowed(earcons_enabled, context) {
        sink.play_blocking(Earcon::Start);
    }
    if mute_while_dictating {
        mute_for_take(context, output)
    } else {
        None
    }
}

/// A take ends (stop or cancel): the output is restored FIRST — unconditionally,
/// whatever the settings say now — and only then does the stop earcon play.
pub fn end_take<S: EarconSink + ?Sized, O: OutputControl + ?Sized>(
    earcons_enabled: bool,
    saved: Option<OutputAudioState>,
    context: TakeContext,
    sink: &S,
    output: &O,
) {
    if let Some(saved) = saved {
        output.restore(saved);
    }
    if earcon_allowed(earcons_enabled, context) {
        sink.play(Earcon::Stop);
    }
}

/// Lifetime word counts that earn the achievement earcon.
pub const WORD_MILESTONES: [i64; 9] = [
    1_000, 5_000, 10_000, 25_000, 50_000, 100_000, 250_000, 500_000, 1_000_000,
];

/// The milestone a take crossed, if any: `before < m <= after`.
pub fn milestone_crossed(before: i64, after: i64) -> Option<i64> {
    WORD_MILESTONES
        .iter()
        .rev()
        .copied()
        .find(|&m| before < m && m <= after)
}

/// After a take lands: the achievement earcon if it crossed a milestone,
/// otherwise the paste earcon if it was pasted, otherwise nothing. At most one
/// sound per take, so a milestone never plays on top of a paste.
pub fn after_take(pasted: bool, words_before: i64, words_after: i64) -> Option<Earcon> {
    if milestone_crossed(words_before, words_after).is_some() {
        Some(Earcon::Achievement)
    } else if pasted {
        Some(Earcon::Paste)
    } else {
        None
    }
}

/// Play a post-take earcon (paste / achievement) through the same gate.
pub fn play_event<S: EarconSink + ?Sized>(
    earcons_enabled: bool,
    context: TakeContext,
    sink: &S,
    earcon: Earcon,
) {
    if earcon_allowed(earcons_enabled, context) {
        sink.play(earcon);
    }
}

/// The app's sink: AppKit's `NSSound`, in-process, on the default output device,
/// so its level is the system volume (the asset itself peaks near -10 dBFS).
pub struct SystemSink;

/// Ceiling on how long `play_blocking` may hold the record-start path, whatever
/// the asset claims. start/stop are 150 ms; this leaves room for the output
/// buffer to drain before the mute.
const BLOCKING_CEILING_MS: u64 = 260;
/// Tail after the asset's own duration, so the last buffer leaves the device
/// before the mute lands on it.
const DRAIN_TAIL_MS: u64 = 40;

impl EarconSink for SystemSink {
    fn play_blocking(&self, earcon: Earcon) {
        // The playing sound is held for the whole wait: dropping a playing
        // NSSound stops it, and the mute must not land before it is over.
        if let Some((_playing, ms)) = imp::play(earcon) {
            let wait = (ms + DRAIN_TAIL_MS).min(BLOCKING_CEILING_MS);
            std::thread::sleep(std::time::Duration::from_millis(wait));
        }
    }

    fn play(&self, earcon: Earcon) {
        // Fire-and-forget: a short-lived thread owns the sound until it ends.
        let _ = std::thread::Builder::new()
            .name("yap-earcon".into())
            .spawn(move || {
                if let Some((_playing, ms)) = imp::play(earcon) {
                    std::thread::sleep(std::time::Duration::from_millis(ms + DRAIN_TAIL_MS));
                }
            });
    }
}

#[cfg(target_os = "macos")]
mod imp {
    use super::Earcon;
    use objc2::rc::Retained;
    use objc2::AllocAnyThread;
    use objc2_app_kit::NSSound;
    use objc2_foundation::NSData;

    /// Start playback. Returns the playing sound (keep it alive until the clip
    /// ends) and the clip's length in ms, or None if AppKit refused it.
    pub(super) fn play(earcon: Earcon) -> Option<(Retained<NSSound>, u64)> {
        let data = NSData::with_bytes(earcon.bytes());
        let sound = NSSound::initWithData(NSSound::alloc(), &data)?;
        let ms = (sound.duration() * 1000.0).max(0.0) as u64;
        if !sound.play() {
            log::warn!("earcon {earcon:?}: NSSound refused to play");
            return None;
        }
        Some((sound, ms))
    }
}

#[cfg(not(target_os = "macos"))]
mod imp {
    use super::Earcon;
    pub(super) fn play(_earcon: Earcon) -> Option<((), u64)> {
        None
    }
}
